#define FONT_OFFSET 0x20U
#define FONT_CHAR_W  5U
#define FONT_CHAR_H  8U   /* one page = 8 rows */
#define FONT_CELL_W  6U   /* includes 1-pixel gap */

/* ------------------------------------------------------------------ */
/*  Framebuffer                                                        */
/* ------------------------------------------------------------------ */
static uint8_t s_fb[OLED_PAGES][OLED_WIDTH];  /* [page][col] */

/* ------------------------------------------------------------------ */
/*  Low-level I2C helpers                                             */
/* ------------------------------------------------------------------ */
static void ssd1306_cmd(uint8_t cmd)
{
    uint8_t buf[2] = { SSD1306_CTRL_CMD, cmd };
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR << 1U,
                             buf, sizeof(buf), HAL_MAX_DELAY);
}

/* ------------------------------------------------------------------ */
/*  Initialisation sequence                                           */
/* ------------------------------------------------------------------ */
void OLED_Init(void)
{
    HAL_Delay(100); /* Allow display VCC to settle */

    ssd1306_cmd(0xAEU); /* Display off              */
    ssd1306_cmd(0xD5U); /* Set display clock div    */
    ssd1306_cmd(0x80U); /*  – divide ratio = 1, osc freq = 8 */
    ssd1306_cmd(0xA8U); /* Set multiplex ratio       */
    ssd1306_cmd(0x3FU); /*  – 64MUX                  */
    ssd1306_cmd(0xD3U); /* Set display offset        */
    ssd1306_cmd(0x00U); /*  – no offset              */
    ssd1306_cmd(0x40U); /* Set display start line = 0 */
    ssd1306_cmd(0x8DU); /* Charge pump               */
    ssd1306_cmd(0x14U); /*  – enable                 */
    ssd1306_cmd(0x20U); /* Memory addressing mode    */
    ssd1306_cmd(0x00U); /*  – horizontal addressing  */
    ssd1306_cmd(0xA1U); /* Segment remap col127→SEG0 */
    ssd1306_cmd(0xC8U); /* COM scan direction: reverse */
    ssd1306_cmd(0xDAU); /* Set COM pins config        */
    ssd1306_cmd(0x12U); /*  – alt config, disable remap */
    ssd1306_cmd(0x81U); /* Set contrast              */
    ssd1306_cmd(0xCFU); /*  – 0xCF                   */
    ssd1306_cmd(0xD9U); /* Set pre-charge period      */
    ssd1306_cmd(0xF1U); /*  – phase1=1, phase2=15     */
    ssd1306_cmd(0xDBU); /* Set VCOMH deselect level   */
    ssd1306_cmd(0x40U); /*  – 0.89 × Vcc             */
    ssd1306_cmd(0xA4U); /* Entire display on (resume) */
    ssd1306_cmd(0xA6U); /* Normal display (non-inverse)*/
    ssd1306_cmd(0xAFU); /* Display on                 */

    OLED_Clear();
    OLED_Update();
}

/* ------------------------------------------------------------------ */
/*  Framebuffer operations                                            */
/* ------------------------------------------------------------------ */
void OLED_Clear(void)
{
    memset(s_fb, 0, sizeof(s_fb));
}

void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) { return; }
    /* Each page is 8 pixels tall; page index and bit offset within page */
    uint8_t page = y / 8U;
    uint8_t bit  = y % 8U;
    if (color) {
        s_fb[page][x] |=  (uint8_t)(1U << bit);
    } else {
        s_fb[page][x] &= ~(uint8_t)(1U << bit);
    }
}

void OLED_DrawChar(uint8_t col, uint8_t page, char ch)
{
    if (page >= OLED_PAGES) { return; }

    uint8_t idx = (uint8_t)ch;
    if (idx < FONT_OFFSET || idx > 0x7EU) { idx = FONT_OFFSET; } /* blank */

    uint8_t font_idx = idx - FONT_OFFSET;
    uint8_t x_start  = col * FONT_CELL_W;

    if (x_start + FONT_CHAR_W > OLED_WIDTH) { return; }

    for (uint8_t i = 0; i < FONT_CHAR_W; i++) {
        s_fb[page][x_start + i] = k_font5x7[font_idx][i];
    }
    /* Gap column */
    if (x_start + FONT_CHAR_W < OLED_WIDTH) {
        s_fb[page][x_start + FONT_CHAR_W] = 0x00U;
    }
}

void OLED_DrawString(uint8_t col, uint8_t page, const char *str)
{
    if (!str) { return; }
    while (*str && col < (OLED_WIDTH / FONT_CELL_W)) {
        OLED_DrawChar(col++, page, *str++);
    }
}

void OLED_DrawProgressBar(uint8_t x, uint8_t y, uint8_t width,
                          uint8_t height, uint8_t pct)
{
    if (pct > 100U) { pct = 100U; }
    uint8_t fill = (uint8_t)((uint16_t)width * pct / 100U);

    for (uint8_t row = y; row < y + height && row < OLED_HEIGHT; row++) {
        for (uint8_t col = x; col < x + width && col < OLED_WIDTH; col++) {
            OLED_DrawPixel(col, row, col < x + fill ? 1U : 0U);
        }
    }
}

/* ------------------------------------------------------------------ */
/*  Flush framebuffer to display                                      */
/* ------------------------------------------------------------------ */
void OLED_Update(void)
{
    /* Set full display window */
    ssd1306_cmd(0x21U); /* Column address */
    ssd1306_cmd(0x00U); /* Start = 0      */
    ssd1306_cmd(0x7FU); /* End   = 127    */
    ssd1306_cmd(0x22U); /* Page address   */
    ssd1306_cmd(0x00U); /* Start = 0      */
    ssd1306_cmd(0x07U); /* End   = 7      */

    /*
     * Transfer each page.  The SSD1306 expects a control byte (0x40)
     * followed by up to 128 data bytes per I2C transaction.
     * We build a 129-byte packet: [0x40, col0, col1, …, col127].
     */
    uint8_t tx_buf[OLED_WIDTH + 1U];
    tx_buf[0] = SSD1306_CTRL_DATA;

    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        memcpy(&tx_buf[1], s_fb[page], OLED_WIDTH);
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR << 1U,
                                 tx_buf, sizeof(tx_buf), HAL_MAX_DELAY);
    }
}
